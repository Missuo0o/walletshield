import { readFile, writeFile, mkdir } from 'node:fs/promises';
import solc from 'solc';
import { createPublicClient, createWalletClient, http, keccak256 } from 'viem';
import { foundry } from 'viem/chains';
const rpc = http('http://127.0.0.1:8545', { timeout: 5000, retryCount: 0 });
const client = createPublicClient({ chain: foundry, transport: rpc });
if (await client.getChainId() !== 31337) throw new Error('Refusing deployment: expected local chain 31337.');
const wallet = createWalletClient({ chain: foundry, transport: rpc });
const [owner, spender] = await wallet.getAddresses();
if (!owner || !spender) throw new Error('Local test accounts unavailable.');
const source = await readFile(new URL('../contracts/TestUSD.sol', import.meta.url), 'utf8');
const output = JSON.parse(solc.compile(JSON.stringify({ language: 'Solidity', sources: { 'TestUSD.sol': { content: source } }, settings: { evmVersion: 'cancun', outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } } } })));
const errors = (output.errors ?? []).filter((e: { severity: string }) => e.severity === 'error');
if (errors.length) throw new Error(JSON.stringify(errors));
const compiled = output.contracts['TestUSD.sol'].TestUSD;
const hash = await wallet.deployContract({ account: owner, abi: compiled.abi, bytecode: `0x${compiled.evm.bytecode.object}`, args: [owner] });
const receipt = await client.waitForTransactionReceipt({ hash });
if (!receipt.contractAddress || receipt.status !== 'success') throw new Error('Deployment failed.');
const code = await client.getCode({ address: receipt.contractAddress });
if (!code) throw new Error('Deployed bytecode unavailable.');
const deployment = { chainId: 31337, token: receipt.contractAddress, owner, spender, tokenCodeHash: keccak256(code), deployedAt: new Date().toISOString() };
await mkdir(new URL('../.local/', import.meta.url), { recursive: true });
await writeFile(new URL('../.local/deployment.json', import.meta.url), JSON.stringify(deployment, null, 2));
console.log(`Local TEST-USD deployed at ${deployment.token}. Owner ${owner} holds 5,000 TEST-USD. No real funds.`);
const {deployLab}=await import('../src/testing/contracts.js');
await deployLab();console.log('WalletShield wallet test contracts deployed.');
